// Generates THIRD_PARTY_NOTICES.md: every package that ships with Konto (the
// backend's production dependencies and the frontend's runtime dependencies,
// bundled into frontend/dist), with its license and license text.
//
// Usage (after `npm install` in backend/ and frontend/):
//   node scripts/third-party-notices.mjs

import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const PARTS = [
  { dir: "backend", label: "Backend (Node.js server)" },
  { dir: "frontend", label: "Frontend (bundled into the web app)" },
];
const LICENSE_FILE = /^(licen[sc]e|copying|notice)(\.(md|txt|markdown))?$/i;

// Installed production packages of a workspace, as absolute paths.
function productionPackages(dir) {
  const output = execFileSync("npm", ["ls", "--omit=dev", "--all", "--parseable"], {
    cwd: join(ROOT, dir),
    encoding: "utf8",
  });
  return output.trim().split("\n").slice(1); // the first line is the workspace itself
}

function describe(path) {
  const pkg = JSON.parse(readFileSync(join(path, "package.json"), "utf8"));
  const license =
    typeof pkg.license === "string" ? pkg.license : pkg.license?.type ?? pkg.licenses?.[0]?.type ?? "UNKNOWN";
  const repository = typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url;
  const url = (pkg.homepage || repository || `https://www.npmjs.com/package/${pkg.name}`)
    .replace(/^git\+/, "")
    .replace(/^git:\/\//, "https://")
    .replace(/\.git$/, "");
  const files = readdirSync(path).filter((name) => LICENSE_FILE.test(name)).sort();
  const text = files.map((name) => readFileSync(join(path, name), "utf8").trim()).join("\n\n");
  return { name: pkg.name, version: pkg.version, license, url, text };
}

const sections = [];
const seen = new Map();
for (const { dir, label } of PARTS) {
  if (!existsSync(join(ROOT, dir, "node_modules"))) {
    console.error(`Run npm install in ${dir}/ first.`);
    process.exit(1);
  }
  const packages = [...new Map(productionPackages(dir).map(describe).map((p) => [`${p.name}@${p.version}`, p])).values()]
    .sort((a, b) => a.name.localeCompare(b.name));
  for (const p of packages) seen.set(`${p.name}@${p.version}`, p);
  sections.push({ label, packages });
}

const licenseCounts = {};
for (const p of seen.values()) licenseCounts[p.license] = (licenseCounts[p.license] ?? 0) + 1;

const lines = [
  "# Third-party notices",
  "",
  "Konto is distributed under the [MIT License](LICENSE). It includes the open-source packages listed below, each under its own license.",
  "",
  "This file is generated by `node scripts/third-party-notices.mjs`: do not edit it by hand. The Docker image is also built on the official `node` image (Debian), which carries its own licenses.",
  "",
  `Summary: ${Object.entries(licenseCounts)
    .sort((a, b) => b[1] - a[1])
    .map(([license, count]) => `${license} (${count})`)
    .join(", ")}.`,
  "",
];
for (const { label, packages } of sections) {
  lines.push(`## ${label}`, "", "| Package | Version | License |", "| --- | --- | --- |");
  for (const p of packages) lines.push(`| [${p.name}](${p.url}) | ${p.version} | ${p.license} |`);
  lines.push("");
}
lines.push("## License texts", "");
for (const p of [...seen.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))) {
  lines.push(`### ${p.name} ${p.version}`, "");
  lines.push(p.text ? ["```text", p.text, "```"].join("\n") : `License: ${p.license} (no license file in the package).`);
  lines.push("");
}

writeFileSync(join(ROOT, "THIRD_PARTY_NOTICES.md"), lines.join("\n"));
console.log(`THIRD_PARTY_NOTICES.md: ${seen.size} packages.`);
